import { defineConfig } from 'vite';
import laravel from 'laravel-vite-plugin';

// Vite используется только локально/в CI: на хостинг заливаются уже
// собранные файлы public/build, Node на сервере не нужен (Этап 1 плана)
export default defineConfig({
    plugins: [
        laravel({
            input: [
                'resources/css/app.css',
                'resources/js/app.js',
                'resources/js/admin.js',
            ],
            refresh: true,
        }),
    ],

    build: {
        // Нижняя граница полноценного сайта — Safari 11 / iOS 11.
        // Ограничение ставит Alpine (см. про async ниже), а не сборка.
        // Всё, что старше, получает ES5-деградацию из layouts/site.blade.php
        // (класс xi-no-alpine): нативный аудиоплеер и развёрнутое меню.
        // Заодно это ровно та граница, ниже которой нет и <script type="module">
        // (Safari 10.1), а Vite собирает только модули.
        //
        // Без этой строки Vite 8 берёт дефолт `baseline-widely-available`
        // (~Safari 16). Проверено парсером: собранный так бандл НЕ разбирается
        // даже как ES2019 — то есть Safari <=13.0 падает с SyntaxError на
        // разборе и не выполняет файл ЦЕЛИКОМ, вместе с Alpine. Страница
        // остаётся без плеера, без мобильного меню и с намертво скрытыми
        // x-cloak элементами. С этим target `?.` и `??` из бандла уходят.
        //
        // Цена для современных браузеров — около 800 байт gzip на JS
        // (rolldown понижает синтаксис и выносит общий хелпер в отдельный
        // чанк objectSpread2 ~0,6 КБ gzip).
        //
        // НЕ опускать ниже es2017: async-функции должны остаться нативными.
        // Alpine строит вычислитель выражений через
        //     Object.getPrototypeOf(async function () {}).constructor
        // и ждёт от него промис. Если async понижен, там оказывается обычный
        // Function, выражение возвращает не промис, и Alpine падает на КАЖДОМ
        // выражении с `r.call(...).catch is not a function` — умирают все
        // компоненты разом, включая плеер, меню и переключатель темы.
        // Именно поэтому в списке safari11, а не safari10.1: по данным oxc
        // async считается доступным с Safari 11, и от safari10.1 он начинает
        // понижать async со всеми последствиями выше. Сам Safari 10.1 async
        // умеет, так что выдаваемый код ему по силам, но гарантировать это
        // мы не будем — для 10.1 и ниже есть деградация.
        target: ['es2017', 'safari11', 'ios11'],

        // CSS задаётся ОТДЕЛЬНО от JS и намеренно опущен ниже: стили получают
        // ВСЕ устройства, включая iOS 9-10, которым бандл не достаётся вовсе —
        // для них корректный CSS это единственное, что делает сайт похожим на
        // сайт. Цена — около 0,9 КБ gzip к исходным 17,1 КБ.
        //
        // Что это даёт помимо размера — минификатор Vite ориентируется на
        // cssTarget и при современном значении САМ ВЫРЕЗАЕТ ненужные, по его
        // мнению, префиксы и не понижает новые свойства:
        //   * `-webkit-backdrop-filter` — без него все 13 матовых панелей
        //     полностью прозрачны на Safari ниже 18 (беспрефиксный вариант
        //     только с Safari 18, то есть страдает и живой iOS 16-17);
        //   * `-webkit-sticky` — липкая шапка на Safari <=12;
        //   * `inset: 0` — 12 мест на абсолютных подложках (аура светлой темы,
        //     звёздное небо, фоны модалок). Safari <14.1 свойство игнорирует и
        //     слои схлопываются; здесь оно раскладывается в top/right/bottom/left.
        cssTarget: ['safari9', 'ios9'],

        // Safari 10 не понимает <link rel="modulepreload">, а полифилл-шим Vite
        // тянет за собой лишний код в самом начале загрузки. На нашем объёме
        // ассетов выигрыш от preload — единицы миллисекунд, надёжность важнее.
        modulePreload: { polyfill: false },
    },
});
